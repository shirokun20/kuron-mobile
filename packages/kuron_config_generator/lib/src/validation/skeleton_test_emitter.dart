import 'dart:io';

/// Emits a skeleton verification test next to the generated config.
///
/// The test is dual-mode:
/// - default: replays golden fixtures through a fail-fast offline Dio adapter
///   (CI-safe — no site HTTP can escape); screens without fixtures are skipped
/// - LIVE=1 env: hits the real site instead of fixtures
class SkeletonTestEmitter {
  SkeletonTestEmitter({required this.outputDir, required this.sourceId});

  final String outputDir;
  final String sourceId;

  void write() {
    final file = File('$outputDir/${sourceId}_generated_live_test.dart');
    file.writeAsStringSync(_template());
  }

  String _template() => '''
// GENERATED by kuron_config_generator — verification test for `$sourceId`.
//
// Dual-mode:
//   default        : replay golden fixtures offline (no real HTTP), skip
//                    screens without a fixture
//   LIVE=1 dart test : hit the real site
//
// Regenerate via: fvm dart run bin/kuron_config_generator.dart generate \\
//   --url <baseUrl> --validate --live
library;

import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:dio/dio.dart';
import 'package:kuron_core/kuron_core.dart';
import 'package:kuron_generic/kuron_generic.dart';
import 'package:logger/logger.dart';
import 'package:test/test.dart';

const _sourceId = '$sourceId';
final _live = Platform.environment['LIVE'] == '1';

const _defaultExtensionsDir =
    '/Users/asix/Documents/ektensi/kuron-extensions';

/// READ-ONLY local kuron-extensions checkout — configs are never copied into
/// (or committed to) this repo. CI without the checkout skips via StateError.
Map<String, Object?> _loadConfig() {
  final extensionsDir =
      Platform.environment['KURON_EXTENSIONS_DIR'] ?? _defaultExtensionsDir;
  final candidates = <String>[
    'build/generated/\$_sourceId-config.json',
    for (final lang in <String>['en', 'id', 'global', 'ja', 'vi', 'ch', 'new'])
      '\$extensionsDir/config/\$lang/\$_sourceId-config.json',
  ];
  for (final path in candidates) {
    final f = File(path);
    if (f.existsSync()) {
      return (jsonDecode(f.readAsStringSync()) as Map).cast<String, Object?>();
    }
  }
  throw StateError('config unavailable: \$_sourceId-config.json');
}

String? _fixture(String screen) {
  if (_live) return null;
  final candidates = [
    'build/generated/fixtures/\$_sourceId/\$screen.html',
    'fixtures/\$_sourceId/\$screen.html',
    'test/integration/fixtures/\$_sourceId/\$screen.html',
  ];
  for (final path in candidates) {
    final f = File(path);
    if (f.existsSync()) return f.readAsStringSync();
  }
  return null;
}

/// List (non-detail/chapter) URL patterns from the config. Anything outside
/// these patterns is unmocked and fails fast in offline mode.
List<RegExp> _listPatterns(Map<String, Object?> config) {
  final patterns =
      ((config['scraper'] as Map?)?['urlPatterns'] as Map?) ?? const {};
  final result = <RegExp>[];
  for (final entry in patterns.entries) {
    final key = entry.key.toString().toLowerCase();
    if (key.startsWith('detail') || key.startsWith('chapter')) continue;
    final raw = switch (entry.value) {
      final String s => s,
      final Map m => m['url']?.toString() ?? '',
      _ => '',
    };
    if (raw.isEmpty) continue;
    final parts = raw.split(RegExp(r'\\{[^}]+\\}'));
    final source = parts.map(RegExp.escape).join(r'.+?');
    if (source.isNotEmpty) result.add(RegExp(source));
  }
  return result;
}

/// Offline Dio adapter: replays the home fixture on list URLs, throws on any
/// other request so no HTTP escapes the test process.
class _FixtureAdapter implements HttpClientAdapter {
  _FixtureAdapter(this.body, this.allowed);

  final String body;
  final List<RegExp> allowed;

  @override
  Future<ResponseBody> fetch(RequestOptions options,
      Stream<Uint8List>? requestStream, Future<void>? cancelFuture) async {
    final url = options.uri.toString();
    if (options.method.toUpperCase() == 'GET' &&
        allowed.any((r) => r.hasMatch(url))) {
      return ResponseBody.fromString(
        body,
        200,
        headers: {Headers.contentTypeHeader: ['text/html; charset=utf-8']},
      );
    }
    throw StateError('Offline replay: unmocked \${options.method} request \$url');
  }

  @override
  void close({bool force = false}) {}
}

bool _canReplay(Map<String, Object?> config, String screen) {
  if (_live) return true;
  final home = _fixture('home');
  if (home == null) return false;
  // Stale fixture (config container no longer in saved HTML) is a skip.
  final homeCfg = ((config['scraper'] as Map?)?['urlPatterns'] as Map?)?['home'];
  String? container;
  if (homeCfg is Map) {
    final list = homeCfg['list'];
    if (list is Map) container = list['container']?.toString();
  }
  final token = container == null
      ? null
      : RegExp(r'[.]([A-Za-z0-9_-]+)').firstMatch(container)?.group(1);
  if (token != null && token.isNotEmpty && !home.contains(token)) return false;
  if (screen == 'home') return true;
  if (screen == 'search') return _fixture('search') != null;
  if (_fixture('detail') == null) return false;
  if (screen == 'detail') return true;
  final reader =
      ((config['scraper'] as Map?)?['selectors'] as Map?)?['reader'];
  final mode = reader is Map ? reader['mode']?.toString() : null;
  if (mode == 'hentaifoxCdn' || mode == 'gallery') return true;
  return _fixture('reader') != null;
}

GenericScraperAdapter _adapter(Map<String, Object?> config,
    {HttpClientAdapter? httpAdapter}) {
  final baseUrl = config['baseUrl'] as String;
  final dio = Dio(BaseOptions(
    baseUrl: baseUrl,
    connectTimeout: const Duration(seconds: 30),
    receiveTimeout: const Duration(seconds: 60),
    headers: ((config['network'] as Map?)?['headers'] as Map?)
        ?.cast<String, dynamic>(),
    validateStatus: (s) => s != null && s < 500,
  ));
  if (httpAdapter != null) {
    dio.httpClientAdapter = httpAdapter;
  }
  return GenericScraperAdapter(
    dio: dio,
    urlBuilder: GenericUrlBuilder(baseUrl: baseUrl),
    parser: GenericHtmlParser(logger: Logger(level: Level.off)),
    logger: Logger(level: Level.off),
    sourceId: config['source'] as String,
  );
}

void main() {
  String? unavailable;
  late Map<String, Object?> config;
  late GenericScraperAdapter adapter;
  try {
    config = _loadConfig();
    final home = _fixture('home');
    adapter = _adapter(
      config,
      httpAdapter: _live || home == null
          ? null
          : _FixtureAdapter(home, _listPatterns(config)),
    );
  } on StateError catch (e) {
    unavailable = e.message;
  }

  group('\$_sourceId generated 5-screen', () {
    test('home screen returns items', () async {
      final fixture = _fixture('home');
      if (!_canReplay(config, 'home')) {
        markTestSkipped('no usable home fixture for \$_sourceId; re-run with LIVE=1');
        return;
      }
      if (fixture != null) {
        expect(fixture, contains('<html'), reason: 'home fixture sanity');
      }
      final result = await adapter.search(
        const SearchFilter(query: '', page: 1),
        config,
      );
      if (!_live && result.items.isEmpty) {
        markTestSkipped(
            'stale home fixture: no items parsed with current config');
        return;
      }
      expect(result.items, isNotEmpty, reason: 'home items');
      expect(result.items.first.id, isNotEmpty);
      expect(result.items.first.title, isNotEmpty);
      for (final item in result.items) {
        // Stale fixtures may lack covers; only assert absolute when present.
        if (!_live && item.coverUrl.isEmpty) continue;
        expect(item.coverUrl.startsWith('http'), isTrue,
            reason: 'cover must be absolute: \${item.coverUrl}');
      }
    }, timeout: const Timeout(Duration(seconds: 90)));

    test('search screen returns results', () async {
      if (!_canReplay(config, 'search')) {
        markTestSkipped('no offline search fixture; re-run with LIVE=1');
        return;
      }
      final result = await adapter.search(
        const SearchFilter(query: 'a', page: 1),
        config,
      );
      expect(result.items, isNotEmpty, reason: 'search "a"');
    }, timeout: const Timeout(Duration(seconds: 90)));

    test('detail screen parses title and pages/chapters', () async {
      if (!_canReplay(config, 'detail')) {
        markTestSkipped('no offline detail fixture; re-run with LIVE=1');
        return;
      }
      final home = await adapter.search(
        const SearchFilter(query: '', page: 1),
        config,
      );
      final id = home.items.first.id;
      final detail = await adapter.fetchDetail(id, config);
      expect(detail.content.title, isNotEmpty, reason: 'detail title for \$id');
      final hasPages = detail.content.pageCount > 0 ||
          detail.imageUrls.isNotEmpty ||
          (detail.content.chapters?.isNotEmpty ?? false);
      expect(hasPages, isTrue, reason: 'detail has pages or chapters');
    }, timeout: const Timeout(Duration(seconds: 90)));

    test('chapters + reader images resolve', () async {
      if (!_canReplay(config, 'reader')) {
        markTestSkipped('no offline reader fixture; re-run with LIVE=1');
        return;
      }
      final home = await adapter.search(
        const SearchFilter(query: '', page: 1),
        config,
      );
      final detail = await adapter.fetchDetail(home.items.first.id, config);
      final chapters = detail.content.chapters;
      if (chapters == null || chapters.isEmpty) {
        final data =
            await adapter.fetchChapterImages(home.items.first.id, config);
        expect(data?.images, isNotEmpty, reason: 'gallery reader images');
      } else {
        final data =
            await adapter.fetchChapterImages(chapters.first.id, config);
        expect(data?.images, isNotEmpty, reason: 'reader images');
      }
    }, timeout: const Timeout(Duration(seconds: 120)));
  }, skip: unavailable);
}
''';
}
